// Draws the demo's sample documents (ID cards, workplace photos) as JPEGs, and the scanned
// application form as a PDF. Every sample is marked SAMPLE. Demo only.
import { amountInWords } from "../lib/amountInWords";
import { buildPdf, type PdfImage, type PdfLine } from "./samplePdf";

const WIDTH = 1000;
const HEIGHT = 630;

function canvas(width = WIDTH, height = HEIGHT) {
  const surface = new OffscreenCanvas(width, height);
  const context = surface.getContext("2d")!;
  return { surface, context };
}

function sampleWatermark(context: OffscreenCanvasRenderingContext2D, width = WIDTH, height = HEIGHT) {
  context.save();
  context.translate(width / 2, height / 2);
  context.rotate(-0.35);
  context.font = "bold 120px Helvetica, Arial, sans-serif";
  context.fillStyle = "rgba(200, 30, 30, 0.16)";
  context.textAlign = "center";
  context.fillText("SAMPLE", 0, 40);
  context.restore();
}

function cardBackground(context: OffscreenCanvasRenderingContext2D) {
  const gradient = context.createLinearGradient(0, 0, WIDTH, HEIGHT);
  gradient.addColorStop(0, "#f4f1de");
  gradient.addColorStop(1, "#dfe9d3");
  context.fillStyle = "#e9e4cf";
  context.fillRect(0, 0, WIDTH, HEIGHT);
  context.fillStyle = gradient;
  context.beginPath();
  context.roundRect(20, 20, WIDTH - 40, HEIGHT - 40, 28);
  context.fill();
  // Black, yellow and red bands along the top
  ["#1f1f1f", "#f2c200", "#c8102e"].forEach((colour, index) => {
    context.fillStyle = colour;
    context.fillRect(20, 20 + index * 14, WIDTH - 40, 14);
  });
}

const jpeg = (surface: OffscreenCanvas) => surface.convertToBlob({ type: "image/jpeg", quality: 0.85 });

export function nationalIdFront(name: string, nin: string) {
  const { surface, context } = canvas();
  cardBackground(context);
  context.fillStyle = "#1f2937";
  context.font = "bold 34px Helvetica, Arial, sans-serif";
  context.fillText("THE REPUBLIC OF UGANDA", 60, 120);
  context.font = "24px Helvetica, Arial, sans-serif";
  context.fillText("NATIONAL IDENTITY CARD", 60, 156);

  // Photo
  context.fillStyle = "#cbd5c0";
  context.fillRect(60, 190, 230, 290);
  context.fillStyle = "#8a9a7b";
  context.beginPath();
  context.arc(175, 290, 62, 0, Math.PI * 2);
  context.fill();
  context.beginPath();
  context.ellipse(175, 455, 100, 70, 0, Math.PI, 0);
  context.fill();

  const [given, ...surname] = name.split(" ");
  const field = (label: string, value: string, y: number) => {
    context.fillStyle = "#4b5563";
    context.font = "20px Helvetica, Arial, sans-serif";
    context.fillText(label, 330, y);
    context.fillStyle = "#111827";
    context.font = "bold 32px Helvetica, Arial, sans-serif";
    context.fillText(value, 330, y + 38);
  };
  field("SURNAME", surname.join(" ").toUpperCase(), 220);
  field("GIVEN NAME", given.toUpperCase(), 310);
  field("NIN", nin, 400);
  context.fillStyle = "#4b5563";
  context.font = "18px Helvetica, Arial, sans-serif";
  context.fillText("Demo document generated by Tamu Loans", 330, 540);
  sampleWatermark(context);
  return jpeg(surface);
}

export function nationalIdBack(nin: string) {
  const { surface, context } = canvas();
  cardBackground(context);
  // Barcode
  let x = 80;
  for (let i = 0; i < 70; i++) {
    const barWidth = 2 + ((i * 7 + nin.charCodeAt(i % nin.length)) % 6);
    context.fillStyle = "#111827";
    context.fillRect(x, 120, barWidth, 150);
    x += barWidth + 4;
    if (x > WIDTH - 100) break;
  }
  context.font = "28px Menlo, Consolas, monospace";
  context.fillStyle = "#111827";
  const machineLines = [`IDUGA${nin}<<<<<<<<<<<<`, "SAMPLE<<DOCUMENT<<<<<<<<<<<<", "TAMU<<LOANS<<DEMO<<<<<<<<<<<"];
  machineLines.forEach((line, index) => context.fillText(line, 80, 400 + index * 48));
  sampleWatermark(context);
  return jpeg(surface);
}

export function workplacePhoto(location: string, occupation: string) {
  const { surface, context } = canvas();
  const sky = context.createLinearGradient(0, 0, 0, HEIGHT);
  sky.addColorStop(0, "#9cc9f5");
  sky.addColorStop(1, "#e8f2fc");
  context.fillStyle = sky;
  context.fillRect(0, 0, WIDTH, HEIGHT);
  context.fillStyle = "#b9a58a";
  context.fillRect(0, 470, WIDTH, 160);
  // Shop front
  context.fillStyle = "#f6efe2";
  context.fillRect(220, 170, 560, 300);
  context.fillStyle = "#2185f6";
  context.fillRect(200, 140, 600, 80);
  context.fillStyle = "#fff";
  context.font = "bold 34px Helvetica, Arial, sans-serif";
  context.textAlign = "center";
  context.fillText(occupation.toUpperCase(), WIDTH / 2, 192);
  context.fillStyle = "#6b4f33";
  context.fillRect(440, 300, 120, 170);
  context.fillStyle = "#cfe3f7";
  context.fillRect(260, 260, 140, 110);
  context.fillRect(600, 260, 140, 110);
  context.fillStyle = "#1f2937";
  context.font = "26px Helvetica, Arial, sans-serif";
  context.fillText(location, WIDTH / 2, 560);
  sampleWatermark(context);
  return jpeg(surface);
}

// ---------- Tamu's forms (loan-docs/), filled in ----------

const ugx = (amount: number) => `UGX ${Math.round(amount).toLocaleString("en-US")}`;
const longDate = (iso: string) => new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
const addDays = (iso: string, days: number) => new Date(new Date(iso).getTime() + days * 86_400_000).toISOString();

/** Splits text into lines short enough for the page (the PDF builder doesn't wrap). */
function wrap(text: string, width = 92) {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    if (`${line} ${word}`.trim().length > width) {
      lines.push(line);
      line = word;
    } else line = `${line} ${word}`.trim();
  }
  if (line) lines.push(line);
  return lines;
}

const paragraph = (text: string, gap = 22) => wrap(text).map((line, index) => ({ text: line, size: 10, gap: index === 0 ? gap : 14 }));

interface FormLoan {
  reference: string;
  amount: number;
  dateBorrowed: string;
  schedule: "daily" | "weekly" | "monthly";
  guarantors: { name: string; nin: string; phone: string }[];
  /** Set when the officer chose the dates (new applications); otherwise worked out from the frequency */
  firstPaymentOn?: string;
  lastPaymentOn?: string;
}

const TERM_DAYS = { daily: 120, weekly: 182, monthly: 182 };
const FREQUENCY = { daily: "Daily", weekly: "Weekly", monthly: "Monthly" };
const signature = (name: string, signedOnline: boolean) => (signedOnline ? `Signed online by ${name} (drawn on screen)` : `Signed on paper by ${name} (scanned copy)`);

/** Page 1: "Money / Amount Owing Payment Agreement", filled in. */
function agreementPage({ borrower, forms, signedOn, signedOnline, signatures }: LoanApplicationInput): PdfLine[] {
  const firstPayment = forms.firstPaymentOn ?? addDays(forms.dateBorrowed, forms.schedule === "daily" ? 1 : forms.schedule === "weekly" ? 7 : 30);
  const lastPayment = forms.lastPaymentOn ?? addDays(forms.dateBorrowed, TERM_DAYS[forms.schedule]);
  return [
    { text: "Money / Amount Owing Payment Agreement", size: 14, gap: 0 },
    { text: `${forms.reference} · page 1 of 3 · SAMPLE DOCUMENT generated by the demo, not a real agreement`, size: 8, gap: 16 },
    { text: `Name of Payee (Borrower): ${borrower.name}`, size: 10, gap: 26 },
    { text: `I.D. NIN: ${borrower.nin} (original I.D. provided)`, size: 10 },
    { text: `Shop/Premises/Building/Arcade: ${borrower.premises}`, size: 10 },
    { text: `Telephone number: ${borrower.phone}      Date Borrowed: ${longDate(forms.dateBorrowed)}`, size: 10 },
    { text: `Total Amount (in words and figures): ${amountInWords(forms.amount)} (${ugx(forms.amount)})`, size: 10 },
    { text: `Repayment Date: ${longDate(lastPayment)}`, size: 10 },
    { text: "Agreement Terms:", size: 11, gap: 26 },
    ...paragraph(`I, ${borrower.name} ("Payee"), borrowed ${ugx(forms.amount)} (${amountInWords(forms.amount)}) from TAMU SERVICES UGANDA ("Promisor") on ${longDate(forms.dateBorrowed)}. By signing this agreement both Payee and Promisor acknowledge that Payee will pay back Promisor using the following payment schedule.`, 18),
    { text: `Payment Frequency: ${FREQUENCY[forms.schedule]}`, size: 10, gap: 20 },
    { text: "Payment deposit details: C/O TAMU SERVICES UGANDA (Promisor)", size: 10 },
    ...paragraph(`The payee agrees to repay the Promisor an Interest of 18% Administration charge. The repayments will commence on ${longDate(firstPayment)}, till maturity. The last payment will be made on ${longDate(lastPayment)}, inclusive of Charge and Principal plus any other accrued charges, at which time the loan will be fully repaid. All payments to be made via TAMU SERVICES Merchant Codes as provided.`),
    ...paragraph("FAILURE TO MAKE PAYMENT ON AGREED TIMELINES OUR RECOVERY / LEGAL TEAM WILL BE NOTIFIED TO EFFECT RECOVERY MEASURES AS NECESSARY AND IMMEDIATELY."),
    ...paragraph("Recovery charges will be added as determined by the recovery team to help recover the defaulted amount and the same will be paid by the defaulter at time of recovery. Both the payee and promisor agree on the charges as stated above."),
    { text: `Signing Date: ${longDate(signedOn)}`, size: 10, gap: 24 },
    { text: `Signature of Payee / Borrower: ${signature(borrower.name, signedOnline)}`, size: 10 },
    ...(signatures ? [{ image: signatures.borrower, height: 40 }] : []),
    ...forms.guarantors.flatMap((g, index) => [
      { text: `Guarantor-${index + 1} Name: ${g.name}`, size: 10, gap: index === 0 ? 24 : 18 },
      { text: `ID.No. ${g.nin}     Phone no. ${g.phone}     Sign: ${signedOnline ? "signed online (see consent)" : "signed on paper"}`, size: 10 },
    ]),
  ];
}

/** Pages 2 and 3: "Guarantor Consent and Undertaking to pay TAMU amount in case of default by the Borrower". */
function consentPage({ borrower, forms, signedOn, signedOnline, signatures }: LoanApplicationInput, index: number): PdfLine[] {
  const guarantor = forms.guarantors[index];
  return [
    { text: "Guarantor Consent and Undertaking to pay TAMU amount", size: 13, gap: 0 },
    { text: "in case of default by the Borrower", size: 13, gap: 18 },
    { text: `${forms.reference} · page ${index + 2} of 3 · Guarantor ${index + 1} · SAMPLE DOCUMENT generated by the demo`, size: 8, gap: 16 },
    ...paragraph(`I, ${guarantor.name} of NIN ${guarantor.nin}, has hereby agreed to guarantee ${borrower.name} of NIN ${borrower.nin} for (Amount in words: ${amountInWords(forms.amount)}) Amount in figures: ${ugx(forms.amount)}, the amount borrowed on this date ${longDate(forms.dateBorrowed)} as per agreed terms from TAMU CLEANING SERVICES. In case of any default in payment of the amount plus any accrued charges, I will pay all the amounts owed.`, 30),
    { text: `Sign: ${signature(guarantor.name, signedOnline)}`, size: 10, gap: 30 },
    ...(signatures ? [{ image: signatures.guarantors[index], height: 40 }] : []),
    { text: `Date: ${longDate(signedOn)}`, size: 10 },
  ];
}

interface LoanApplicationInput {
  borrower: { name: string; nin: string; phone: string; premises: string };
  forms: FormLoan;
  signedOn: string;
  signedOnline: boolean;
  /** Drawn on the online form */
  signatures?: { borrower: PdfImage; guarantors: [PdfImage, PdfImage] };
}

/** A loan application: the payment agreement and both guarantor consents, filled in and merged into one PDF. */
export function loanApplicationPdf(input: LoanApplicationInput) {
  return buildPdf([agreementPage(input), consentPage(input, 0), consentPage(input, 1)]);
}
